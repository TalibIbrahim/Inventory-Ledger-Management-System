// Helper to construct dynamic realistic dates
const now = new Date();
const getIsoDate = (daysAgo: number, hoursAgo = 0, minsAgo = 0): string => {
  const d = new Date(now.getTime() - daysAgo * 86400000 - hoursAgo * 3600000 - minsAgo * 60000);
  return d.toISOString();
};

